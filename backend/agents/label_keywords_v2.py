TAXONOMY_NAME_TO_CODE = {name: code for code, name in TAXONOMY_NAMES.items()}


def expand_labels(labels):
    """
    把上游标签（45类编码 / 45类中文名 / 公告研读旧10类 / 原兼容标签）
    统一展开为“原标签 + 45类编码”集合，供案例检索使用。
    """
    out = set()

    for lab in labels:
        lab = str(lab).strip()
        if not lab:
            continue

        out.add(lab)

        # 已经是45类编码，如 C03
        if lab in TAXONOMY_NAMES:
            out.add(lab)

        # “C03 商誉与商誉减值”这类带编码文本
        prefix = lab[:3]
        if prefix in TAXONOMY_NAMES:
            out.add(prefix)

        # 完整中文主题名
        code = TAXONOMY_NAME_TO_CODE.get(lab)
        if code:
            out.add(code)

        # 公告研读Agent旧10类
        for code in ANNOUNCEMENT_CATEGORY_MAP.get(lab, []):
            out.add(code)

        # 原兼容标签
        for code in LEGACY_CATEGORY_MAP.get(lab, []):
            out.add(code)

    return out


